/**
 * Full CareerOS deploy:
 *   1. build the frontend (with whatever frontend/.env.production exists),
 *   2. cdk deploy (writes stack outputs to infra/cdk-outputs.json),
 *   3. write the outputs into frontend/.env.production,
 *   4. if the env file changed: rebuild the frontend and cdk deploy again
 *      (only the BucketDeployment changes, CloudFront cache is invalidated).
 *
 * Usage:
 *   ALERT_EMAIL=you@example.com npm run deploy
 *   npm run deploy -- --alert-email you@example.com
 * Optional: TEAM_EMAILS=a@x.com,b@y.com (team accounts the /admin page can exclude),
 *           ALLOW_LOCAL_DEV=1 (also allow http://localhost:5173 in CORS, for local frontend dev).
 */
import { spawnSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const INFRA_DIR = path.resolve(here, '..');
const REPO_ROOT = path.resolve(INFRA_DIR, '..');
const OUTPUTS_FILE = path.join(INFRA_DIR, 'cdk-outputs.json');
const ENV_FILE = path.join(REPO_ROOT, 'frontend', '.env.production');
const STACK_NAME = 'CareerOsStack';

function parseAlertEmail(argv: string[]): string | undefined {
  const i = argv.findIndex((a) => a === '--alert-email' || a === '--alertEmail');
  if (i >= 0) return argv[i + 1];
  const inline = argv.find((a) => a.startsWith('--alert-email=') || a.startsWith('--alertEmail='));
  if (inline) return inline.split('=')[1];
  return process.env.ALERT_EMAIL;
}

function run(cmd: string, args: string[], cwd: string): void {
  console.log(`\n$ ${cmd} ${args.join(' ')}   (in ${path.relative(REPO_ROOT, cwd) || '.'})`);
  const isWin = process.platform === 'win32';
  // With shell: true the args are joined into one command line, so quote any arg with spaces
  // (e.g. a repo path like "C:\Users\me\My Project\...") or it gets split into several args.
  const shellArgs = isWin ? args.map((a) => (/\s/.test(a) ? `"${a}"` : a)) : args;
  const res = spawnSync(cmd, shellArgs, { cwd, stdio: 'inherit', shell: isWin });
  if (res.status !== 0) {
    console.error(`\nCommand failed with exit code ${res.status ?? 'null'}: ${cmd} ${args.join(' ')}`);
    process.exit(res.status ?? 1);
  }
}

function buildFrontend(): void {
  run('npm', ['run', 'build', '--workspace=frontend'], REPO_ROOT);
}

/** Comma-separated team e-mails for the /admin filter (TEAM_EMAILS env), never committed. */
const TEAM_EMAILS = (process.env.TEAM_EMAILS ?? '').trim();

function cdkDeploy(alertEmail: string): void {
  run(
    'npx',
    [
      'cdk',
      'deploy',
      STACK_NAME,
      '--require-approval',
      'never',
      '--outputs-file',
      OUTPUTS_FILE,
      '-c',
      `alertEmail=${alertEmail}`,
      ...(TEAM_EMAILS ? ['-c', `teamEmails=${TEAM_EMAILS}`] : []),
      ...(process.env.ALLOW_LOCAL_DEV === '1' ? ['-c', 'allowLocalDev=true'] : []),
    ],
    INFRA_DIR,
  );
}

function renderEnv(): string {
  const all = JSON.parse(fs.readFileSync(OUTPUTS_FILE, 'utf8')) as Record<
    string,
    Record<string, string>
  >;
  const out = all[STACK_NAME];
  if (!out) throw new Error(`No outputs for ${STACK_NAME} in ${OUTPUTS_FILE}`);
  const required = ['ApiUrl', 'UserPoolId', 'UserPoolClientId', 'Region', 'CloudFrontUrl'] as const;
  for (const key of required) {
    if (!out[key]) throw new Error(`Stack output ${key} is missing`);
  }
  return [
    '# Generated by infra/scripts/deploy.ts from CloudFormation outputs. Do not edit by hand.',
    `VITE_API_URL=${out.ApiUrl}`,
    `VITE_USER_POOL_ID=${out.UserPoolId}`,
    `VITE_USER_POOL_CLIENT_ID=${out.UserPoolClientId}`,
    `VITE_REGION=${out.Region}`,
    // The extension links back to the site (sign-up, full results); the site itself ignores it.
    `VITE_SITE_URL=${out.CloudFrontUrl}`,
    '',
  ].join('\n');
}

function main(): void {
  const alertEmail = parseAlertEmail(process.argv.slice(2));
  if (!alertEmail || !alertEmail.includes('@')) {
    console.error(
      'An e-mail for the AWS budget alert is required.\n' +
        '  ALERT_EMAIL=you@example.com npm run deploy\n' +
        '  npm run deploy -- --alert-email you@example.com',
    );
    process.exit(1);
  }

  buildFrontend();
  cdkDeploy(alertEmail);

  const env = renderEnv();
  const previous = fs.existsSync(ENV_FILE) ? fs.readFileSync(ENV_FILE, 'utf8') : '';
  if (env === previous) {
    console.log('\nfrontend/.env.production is up to date — no second deploy needed.');
  } else {
    fs.writeFileSync(ENV_FILE, env);
    console.log('\nWrote frontend/.env.production — rebuilding and redeploying the frontend.');
    buildFrontend();
    cdkDeploy(alertEmail);
  }

  const out = (JSON.parse(fs.readFileSync(OUTPUTS_FILE, 'utf8')) as Record<string, Record<string, string>>)[
    STACK_NAME
  ]!;
  console.log('\nCareerOS deployed:');
  console.log(`  Site:   ${out.CloudFrontUrl}`);
  console.log(`  API:    ${out.ApiUrl}  (try ${out.ApiUrl}/health)`);
  console.log(`  Region: ${out.Region}`);
}

main();
